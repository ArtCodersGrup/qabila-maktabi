// Yangi versiya fayllari brauzerning oddiy keshidan emas, serverdan olinadi (cache: "reload").
// Aks holda GitHub Pages 10 daqiqa kesh bergani uchun yangi kesh ichiga eski fayllar tushib qoladi.
self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE)
      .then((cache) => cache.addAll(FILES.map((file) => new Request(file, { cache: "reload" }))))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim())
  );
});

// Avval keshdan beramiz (tez va internetsiz ishlaydi), orqa fonda serverdan tekshirib yangilaymiz
self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname.startsWith("/api/")) return; // server javoblari (kirish holati, xonalar) hech qachon keshlanmaydi
  event.respondWith(
    // ignoreSearch: ?bosqich=2 kabi so'rov satri bilan ochilgan o'yin ham keshdagi sahifasini topadi
    // (aks holda internetsiz rejimda o'yin o'rniga bosh sahifa chiqardi)
    caches.open(CACHE).then((cache) => cache.match(request, { ignoreSearch: true }).then((hit) => {
      const fresh = fetch(request, { cache: "no-cache" })
        .then((response) => {
          // So'rov satrli variantlar keshga yozilmaydi — bitta sahifaning nusxalari yig'ilib ketmasin
          if (response && response.ok && !url.search) cache.put(request, response.clone());
          return response;
        })
        .catch(() => hit || (request.mode === "navigate" ? cache.match("index.html") : undefined));
      return hit || fresh;
    }))
  );
});
